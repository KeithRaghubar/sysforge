"""test_build_design.py - tests for tools/build_design.py.

The happy-path test runs the drift check against the real repo and expects the
committed DESIGN.md to match its docs/design/ sources. The behavior tests copy
docs/design/ + DESIGN.md into tmp_path and invoke the generator with
--repo=<tmp_path>, so an edited source makes --check fail until regenerated.
"""
import shutil
import subprocess
import sys
from pathlib import Path


REPO = Path(__file__).resolve().parent.parent
SCRIPT = REPO / "tools/build_design.py"


def run(args=(), repo=None):
    cmd = [sys.executable, str(SCRIPT)]
    if repo is not None:
        cmd.append(f"--repo={repo}")
    cmd.extend(args)
    return subprocess.run(cmd, capture_output=True, text=True, cwd=REPO)


def _clone_design_tree(dst: Path) -> Path:
    """Copy docs/design/ and DESIGN.md into dst so the generator can run there."""
    shutil.copytree(REPO / "docs/design", dst / "docs/design")
    shutil.copyfile(REPO / "DESIGN.md", dst / "DESIGN.md")
    return dst


def test_real_repo_design_is_current():
    r = run(["--check"])
    assert r.returncode == 0, r.stdout + r.stderr
    assert "[OK]" in r.stdout


def test_check_fails_when_source_edited(tmp_path):
    _clone_design_tree(tmp_path)
    # Edit a source without regenerating -> DESIGN.md is now stale.
    src = tmp_path / "docs/design/01-philosophy.md"
    src.write_text(src.read_text() + "\nAn extra design note.\n")
    r = run(["--check"], repo=tmp_path)
    assert r.returncode == 1
    assert "out of date" in (r.stdout + r.stderr)


def test_regenerate_makes_check_pass(tmp_path):
    _clone_design_tree(tmp_path)
    src = tmp_path / "docs/design/01-philosophy.md"
    src.write_text(src.read_text() + "\nAn extra design note.\n")
    # Regenerate, then the drift check passes again.
    assert run([], repo=tmp_path).returncode == 0
    r = run(["--check"], repo=tmp_path)
    assert r.returncode == 0, r.stdout + r.stderr
    assert "An extra design note." in (tmp_path / "DESIGN.md").read_text()


def test_generated_design_starts_with_banner(tmp_path):
    _clone_design_tree(tmp_path)
    run([], repo=tmp_path)
    text = (tmp_path / "DESIGN.md").read_text()
    assert text.startswith("<!-- GENERATED FILE")
    # The original title must immediately follow the banner (content preserved).
    assert "# SysForge Design Document" in text


def test_toc_is_autogenerated(tmp_path):
    _clone_design_tree(tmp_path)
    # A new top-level `## ` section in a source must show up in the regenerated
    # TOC with a slugified anchor, and the placeholder must be consumed.
    extra = tmp_path / "docs/design/99-extra.md"
    extra.write_text("## Brand New Section\n\nbody.\n")
    manifest = tmp_path / "docs/design/_manifest"
    manifest.write_text(manifest.read_text() + "99-extra.md\n")
    assert run([], repo=tmp_path).returncode == 0
    text = (tmp_path / "DESIGN.md").read_text()
    assert "[Brand New Section](#brand-new-section)" in text
    assert "<!--TOC-->" not in text


def _tree_repo(tmp_path: Path) -> Path:
    """A tmp tree with a tiny sysforge/ package beside the design sources."""
    _clone_design_tree(tmp_path)
    pkg = tmp_path / "sysforge"
    (pkg / "primitives").mkdir(parents=True)
    (pkg / "__init__.py").write_text("")
    (pkg / "cli.py").write_text('"""cli.py — the command-line entry."""\n')
    (pkg / "primitives/paths.py").write_text(
        '"""paths.py -- every path constant.\n\nMore detail."""\n')
    return tmp_path


def test_module_tree_is_generated_from_docstrings(tmp_path):
    """4.0.0-DEV7: the hand-kept tree had fallen 80 modules behind. A module's
    first docstring paragraph describes it, its own file name dropped; a
    namespace package (primitives/ has no __init__.py) still appears."""
    repo = _tree_repo(tmp_path)
    assert run([], repo=repo).returncode == 0
    text = (repo / "DESIGN.md").read_text()
    assert "├── cli.py  # the command-line entry" in text
    assert "└── primitives/\n    └── paths.py  # every path constant\n" in text
    assert "<!--MODULE-TREE-->" not in text.splitlines() and "More detail" not in text


def test_new_module_makes_check_fail_until_regenerated(tmp_path):
    repo = _tree_repo(tmp_path)
    assert run([], repo=repo).returncode == 0
    (repo / "sysforge/primitives/new_probe.py").write_text('"""new_probe.py — probes."""\n')
    assert run(["--check"], repo=repo).returncode == 1
    assert run([], repo=repo).returncode == 0
    assert "new_probe.py  # probes" in (repo / "DESIGN.md").read_text()


def test_module_without_docstring_fails_the_build(tmp_path):
    repo = _tree_repo(tmp_path)
    (repo / "sysforge/primitives/bare.py").write_text("X = 1\n")
    r = run([], repo=repo)
    assert r.returncode != 0 and "sysforge/primitives/bare.py" in r.stderr


def test_module_tree_marker_named_in_prose_is_left_alone(tmp_path):
    """Only a marker alone on its line expands: design 17 names it inline, and
    expanding that one injected an unbalanced fence that hid later headings
    from the TOC."""
    repo = _tree_repo(tmp_path)
    extra = repo / "docs/design/99-extra.md"
    extra.write_text("Prose naming `<!--MODULE-TREE-->` inline.\n\n## After The Prose\n")
    manifest = repo / "docs/design/_manifest"
    manifest.write_text(manifest.read_text() + "99-extra.md\n")
    assert run([], repo=repo).returncode == 0
    text = (repo / "DESIGN.md").read_text()
    assert "naming `<!--MODULE-TREE-->` inline" in text
    assert "[After The Prose](#after-the-prose)" in text
