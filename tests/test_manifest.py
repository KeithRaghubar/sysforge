"""
test_manifest.py — unit tests for manifest generation.

All pacman and AUR calls are replaced with injectable fns so no real
system tools are required.
"""
import sys
import io
from contextlib import redirect_stdout, redirect_stderr

import pytest

from unittest.mock import patch
from sysforge.manifest import generate_manifest, _classify, _toml_entry, _make_aur_fn


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

# Fake repo — packages "known" to pacman
REPO_PKGS = {"htop", "neovim", "mold", "pipewire", "wireplumber"}

def mock_pacman(name):
    return name in REPO_PKGS

def mock_aur(name):
    # Stub — returns None (not found) for everything
    return None

def captured_manifest(names, pacman_fn=mock_pacman, aur_fn=mock_aur):
    out = io.StringIO()
    err = io.StringIO()
    with redirect_stdout(out), redirect_stderr(err):
        result = generate_manifest(names, pacman_fn=pacman_fn, aur_fn=aur_fn)
    return result, out.getvalue(), err.getvalue()


# ---------------------------------------------------------------------------
# _classify
# ---------------------------------------------------------------------------

def test_classify_repo():
    repo, aur, unknown = _classify(["htop", "neovim"], mock_pacman, mock_aur)
    assert repo == ["htop", "neovim"]
    assert aur == []
    assert unknown == []

def test_classify_unknown():
    repo, aur, unknown = _classify(["totally-fake-pkg"], mock_pacman, mock_aur)
    assert unknown == ["totally-fake-pkg"]
    assert repo == []
    assert aur == []

def test_classify_aur():
    # mock_aur_real returns a value for known aur packages
    def real_aur(name):
        return name if name in {"mesa-git", "cosmic-comp-git"} else None

    repo, aur, unknown = _classify(
        ["htop", "mesa-git", "nonexistent"],
        mock_pacman, real_aur,
    )
    assert repo == ["htop"]
    assert aur == ["mesa-git"]
    assert unknown == ["nonexistent"]

def test_classify_mixed():
    repo, aur, unknown = _classify(
        ["htop", "fake-pkg", "neovim"],
        mock_pacman, mock_aur,
    )
    assert repo == ["htop", "neovim"]
    assert unknown == ["fake-pkg"]


