"""libLLVM ``std::`` export parity (3.5.0-F4).

Stock ``llvm-libs`` links libLLVM with a ``global: *`` version script, so the
weak libstdc++ members its build happens to emit are exported under the
``LLVM_<maj>.<min>`` node, and a consumer linked against it (repo mesa, or mesa
built in the sandbox against the repo LLVM) can bind ``std::string::_M_replace``
there instead of at ``GLIBCXX_*``. The ``-fprofile-use`` libLLVM inlines those
copies away, so the symbols vanish at the same soname and the consumer gate
refuses the consumer.

The fix is one forwarding thunk per member, exported at a **non-default**
version (``sym@LLVM_<mm>``, the glibc compat-symbol technique): the dynamic
linker resolves an already-linked consumer's ``sym@LLVM_<mm>`` against it, while
static linkers bind new references only to default versions, so the suite linked
in the same build keeps binding ``@GLIBCXX_*`` and ``scan_abi_hazards`` stays
clean. The body is ``endbr64; jmp`` to a ``.symver``-pinned reference to
libstdc++'s own export, a node libLLVM does not have, so it cannot resolve to
itself even when lld merges a component's weak copy of the same name. The
helper label must be ``.globl``: a local one makes the ``.symver`` alias local.

Rules for :data:`STD_EXPORTS`: each entry is a symbol stock libLLVM exports *and*
libstdc++ exports at the given version. The rendered text contains no ``{`` or
``}`` (the CMake hook's one ``${LLVM_SHLIB_SYMBOL_VERSION}`` aside), because it
is pasted into ``prepare()``, whose span the patcher finds by counting braces.
"""

from __future__ import annotations

from dataclasses import dataclass

SENTINEL = "# sysforge: libLLVM std:: export parity (3.5.0-F4)"
TU_FILENAME = "SysforgeStdExports.cpp"
# A subdirectory of llvm-shlib: LLVM's configure (llvm_check_source_file_list)
# rejects any *.c/*.cpp in a target's own directory that add_llvm_library was
# not given, and its glob is not recursive.
TU_RELPATH = f"sysforge/{TU_FILENAME}"

_S = "_ZNSt7__cxx1112basic_stringIcSt11char_traitsIcESaIcEE"
_W = "_ZNSt7__cxx1112basic_stringIwSt11char_traitsIwESaIwEE"


@dataclass(frozen=True)
class StdExport:
    """One libstdc++ member libLLVM re-exports at its own version node."""

    symbol: str
    libstdcxx_version: str


# The basic_string members missing from the PGO libLLVM 23.1.3 that stock
# exports (measured 2026-10-18); mesa 26.2.5's libgallium imports the first and
# fourth. Add a row when Gate 2's parity advisory names a symbol a consumer needs.
STD_EXPORTS: tuple[StdExport, ...] = (
    StdExport(_S + "9_M_assignERKS4_", "GLIBCXX_3.4.21"),
    StdExport(_S + "9_M_appendEPKcm", "GLIBCXX_3.4.21"),
    StdExport(_S + "9_M_mutateEmmPKcm", "GLIBCXX_3.4.21"),
    StdExport(_S + "10_M_replaceEmmPKcm", "GLIBCXX_3.4.21"),
    StdExport(_S + "14_M_replace_auxEmmmc", "GLIBCXX_3.4.21"),
    StdExport(_S + "15_M_replace_coldEPcmPKcmm", "GLIBCXX_3.4.31"),
    StdExport(_S + "7reserveEm", "GLIBCXX_3.4.21"),
    StdExport(_S + "6resizeEmc", "GLIBCXX_3.4.21"),
    StdExport(_S + "4swapERS4_", "GLIBCXX_3.4.21"),
    StdExport(_W + "9_M_mutateEmmPKwm", "GLIBCXX_3.4.21"),
    StdExport(_W + "6resizeEmw", "GLIBCXX_3.4.21"),
)


def _thunk(n: int, e: StdExport) -> list[str]:
    compat, target = f"__sysforge_std_compat_{n}", f"__sysforge_std_target_{n}"
    return [
        "__asm__(",
        f'    ".symver {target}, {e.symbol}@{e.libstdcxx_version}\\n"',
        '    ".text\\n"',
        '    ".p2align 4\\n"',
        f'    ".globl {compat}\\n"',
        f'    ".type {compat}, @function\\n"',
        f'    "{compat}:\\n"',
        '    "  endbr64\\n"',
        f'    "  jmp {target}@PLT\\n"',
        f'    ".size {compat}, .-{compat}\\n"',
        f'    ".symver {compat}, {e.symbol}@" SF_STR(SYSFORGE_SHLIB_NODE) "\\n"',
        ");",
    ]


def render_tu() -> str:
    """The C++ source added to libLLVM: one thunk per :data:`STD_EXPORTS` entry.

    Empty unless x86-64, libstdc++, and ``SYSFORGE_SHLIB_NODE`` (the version
    node, from the CMake hook) are all present.
    """
    lines = [
        "// " + SENTINEL.removeprefix("# ") + ". Generated by sysforge; do not edit.",
        "// Each thunk exports a libstdc++ member under libLLVM's version node at a",
        "// NON-default version: a consumer linked against stock libLLVM resolves it,",
        "// no new link binds to it, and it forwards to libstdc++'s own export.",
        "#include <cstddef>",
        "#if defined(__x86_64__) && defined(__GLIBCXX__) && defined(SYSFORGE_SHLIB_NODE)",
        "#define SF_STR2(x) #x",
        "#define SF_STR(x) SF_STR2(x)",
    ]
    for n, e in enumerate(STD_EXPORTS):
        lines += _thunk(n, e)
    lines.append("#endif")
    return "\n".join(lines) + "\n"


def render_cmake_hook() -> str:
    """The text appended to ``llvm/tools/llvm-shlib/CMakeLists.txt``.

    Self-gating: only libLLVM (``TARGET LLVM``), only an lld link (GNU ld
    mishandles the thunks under LTO), only with a known version node (an empty
    one would assemble ``sym@``), only x86-64.
    """
    return "\n".join([
        "",
        SENTINEL,
        "if(TARGET LLVM AND LLVM_LINKER_IS_LLD AND LLVM_SHLIB_SYMBOL_VERSION",
        '   AND CMAKE_SYSTEM_PROCESSOR MATCHES "^(x86_64|AMD64)$")',
        f"  target_sources(LLVM PRIVATE {TU_RELPATH})",
        f"  set_source_files_properties({TU_RELPATH} PROPERTIES",
        '    COMPILE_DEFINITIONS "SYSFORGE_SHLIB_NODE=${LLVM_SHLIB_SYMBOL_VERSION}")',
        "endif()",
    ]) + "\n"


def render_prepare_block() -> str:
    """The bash appended to the PKGBUILD's ``prepare()``.

    Globs ``$srcdir/llvm-project*`` so a release tarball and a ``-git`` checkout
    both match, and skips a tree without ``llvm-shlib`` (a standalone
    ``clang`` PKGBUILD). The TU is rewritten every time; the hook is appended
    only when ``CMakeLists.txt`` lacks the sentinel, which keeps a second
    ``prepare()`` over the same ``$srcdir`` from doubling it and re-adds it after
    makepkg re-extracts a stock ``CMakeLists.txt`` beside a surviving TU.
    Heredoc terminators sit at column 0, as quoted heredocs require.
    """
    return "\n".join([
        f"  {SENTINEL}",
        "  local _sf_shlib",
        '  for _sf_shlib in "$srcdir"/llvm-project*/llvm/tools/llvm-shlib; do',
        "    [[ -d $_sf_shlib ]] || continue",
        f"    mkdir -p \"$_sf_shlib/{TU_RELPATH.rsplit('/', 1)[0]}\"",
        f"    cat > \"$_sf_shlib/{TU_RELPATH}\" <<'SYSFORGE_TU'",
        render_tu().rstrip("\n"),
        "SYSFORGE_TU",
        f"    grep -qF '{SENTINEL}' \"$_sf_shlib/CMakeLists.txt\" ||",
        "      cat >> \"$_sf_shlib/CMakeLists.txt\" <<'SYSFORGE_CMAKE'",
        render_cmake_hook().rstrip("\n"),
        "SYSFORGE_CMAKE",
        "  done",
    ]) + "\n"
